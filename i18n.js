  const LOCALES = { ja: 'ja-JP', en: 'en-GB' };
  let lang = (navigator.language || '').toLowerCase().startsWith('ja') ? 'ja' : 'en';

  function t(key, ...args) {
    const v = STRINGS[lang][key] ?? STRINGS.en[key];
    if (v === undefined) return key;
    return typeof v === 'function' ? v(...args) : v;
  }

  function setLang(next) {
    if (!STRINGS[next]) return;
    lang = next;
    document.documentElement.lang = next;
    document.title = t('appName');
    // Text in index.html marked with data-t="key"
    document.querySelectorAll('[data-t]').forEach((el) => { el.innerHTML = t(el.dataset.t); });
    document.querySelectorAll('[data-t-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.tAria)); });
  }

  return {
    t,
    setLang,
    get lang() { return lang; },
    get locale() { return LOCALES[lang]; },
    defaultLang: lang,
  };
